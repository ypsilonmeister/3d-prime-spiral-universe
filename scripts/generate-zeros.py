#!/usr/bin/env python3
"""Generate shared/zeta-zeros-1000.js: imaginary parts of the first 1000
non-trivial zeta zeros via mpmath.zetazero, with sanity checks.

Usage:  python3 scripts/generate-zeros.py
        (if mpmath is not installed system-wide, set MPMATH_PATH to a directory containing it)
"""
import os, re, sys

if os.environ.get("MPMATH_PATH"):
    sys.path.insert(0, os.environ["MPMATH_PATH"])
import mpmath

N = 1000
DECIMALS = 8
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "shared", "zeta-zeros-1000.js")
EXISTING = os.path.join(ROOT, "shared", "zeta-zeros.js")

mpmath.mp.dps = 30
zeros = [float(mpmath.zetazero(n).imag) for n in range(1, N + 1)]
rounded = [round(z, DECIMALS) for z in zeros]

# ---- sanity checks ----
assert len(rounded) == N, f"count {len(rounded)} != {N}"
assert all(b > a for a, b in zip(rounded, rounded[1:])), "not strictly increasing"
assert abs(rounded[0] - 14.134725141734693) < 1e-8, f"first zero {rounded[0]}"
with open(EXISTING) as f:
    existing = [float(x) for x in re.findall(r"\d+\.\d+", f.read().split("ZETA_ZEROS")[1].split("=", 1)[1])]
assert len(existing) == 100, f"existing file has {len(existing)} values"
assert abs(rounded[99] - existing[99]) < 1e-6, f"100th mismatch {rounded[99]} vs {existing[99]}"
assert abs(rounded[999] - 1419.4225) < 1e-3, f"1000th zero {rounded[999]}"
max_diff = max(abs(a - b) for a, b in zip(rounded[:100], existing))
assert max_diff < 1e-6, f"first-100 max diff {max_diff}"
print(f"checks OK: n={len(rounded)}, first={rounded[0]}, 100th={rounded[99]} (existing {existing[99]}), "
      f"1000th={rounded[999]}, max|diff| first100 vs existing={max_diff:.2e}")

# ---- write ----
lines = [
    "// Non-trivial zeros of the Riemann zeta function (imaginary parts γ_n), first 1000 zeros",
    f"// Generated by scripts/generate-zeros.py with mpmath {mpmath.__version__} (mpmath.zetazero), rounded to {DECIMALS} decimal places.",
    "// Same format as shared/zeta-zeros.js (which holds the first 100 zeros).",
    "",
    "export const ZETA_ZEROS_1000 = [",
]
for i in range(0, N, 5):
    chunk = ", ".join(f"{z:.{DECIMALS}f}" for z in rounded[i:i + 5])
    lines.append(f"    {chunk}" + ("," if i + 5 < N else ""))
lines.append("];")
with open(OUT, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", OUT)
